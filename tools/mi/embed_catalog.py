#!/usr/bin/env python3
"""Embed the schema-2 preview fixture without adding runtime file permissions."""
import argparse
import configparser
import json
import sqlite3
import sys
sys.dont_write_bytecode = True
from build_catalog_db import build_database
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tests/mi/catalog_sample.json'
TARGET = ROOT / 'src/pc/mod_integrations/mi_catalog_sample.inc'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    assert ')MI_SAMPLE"' not in text
    content = '// Generated by tools/mi/embed_catalog.py. Edit tests/mi/catalog_sample.json.\n'
    content += 'R"MI_SAMPLE(' + text + ')MI_SAMPLE"\n'
    outputs = {TARGET: content}
    bundled = ROOT / 'assets/mi/catalog.json'
    public = json.loads(bundled.read_text(encoding='utf-8'))
    import hashlib
    canonical = json.dumps(public['mods'], ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')
    if public.get('catalog_id') != 'sha256:' + hashlib.sha256(canonical).hexdigest():
        raise SystemExit('Bundled catalog content hash mismatch')
    if public.get('schema_version') != 2 or public.get('catalog_status') != 'complete' or public.get('mod_count') != len(public['mods']):
        raise SystemExit('Invalid bundled catalog')
    database = ROOT / 'assets/mi/catalog.db'
    if not args.check:
        build_database(bundled, database)
    with sqlite3.connect(database.resolve().as_uri() + '?mode=ro', uri=True) as connection:
        metadata = dict(connection.execute('SELECT key,value FROM metadata'))
        if json.loads(metadata.get('catalog_id', 'null')) != public['catalog_id']:
            raise SystemExit('Bundled database source ID is stale')
        if connection.execute('PRAGMA integrity_check').fetchall() != [('ok',)]:
            raise SystemExit('Bundled database is corrupt')
    blob = database.read_bytes()
    encoded = '// Generated from assets/mi/catalog.db by tools/mi/embed_catalog.py.\n'
    encoded += '\n'.join('"' + ''.join('\\x%02x' % b for b in blob[i:i+32]) + '"' for i in range(0,len(blob),32)) + '\n'
    outputs[ROOT / 'src/pc/mod_integrations/mi_catalog_bundled.inc'] = encoded
    languages = []
    for language in ('English', 'Spanish', 'Portuguese'):
        ini = configparser.ConfigParser(interpolation=None)
        ini.optionxform = str
        ini.read(ROOT / ('lang/' + language + '.ini'), encoding='utf-8')
        languages.append(ini['MI_CATALOG'])
    strings = '// Generated by tools/mi/embed_catalog.py from lang/* [MI_CATALOG].\n'
    for key in languages[0]:
        values = [key] + [json.loads(language[key]) for language in languages]
        strings += '{ ' + ', '.join(json.dumps(value, ensure_ascii=False) for value in values) + ' },\n'
    outputs[ROOT / 'src/pc/mod_integrations/mi_catalog_strings.inc'] = strings
    for target, generated in outputs.items():
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != generated:
                raise SystemExit('Embedded MI data is stale; run python tools/mi/embed_catalog.py')
        else:
            target.write_text(generated, encoding='utf-8')


if __name__ == '__main__':
    main()
