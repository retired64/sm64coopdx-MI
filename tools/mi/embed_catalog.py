#!/usr/bin/env python3
"""Embed the schema-2 preview fixture without adding runtime file permissions."""
import argparse
import configparser
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'tests/mi/catalog_sample.json'
TARGET = ROOT / 'src/pc/mod_integrations/mi_catalog_sample.inc'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    assert ')MI_SAMPLE"' not in text
    content = '// Generated by tools/mi/embed_catalog.py. Edit tests/mi/catalog_sample.json.\n'
    content += 'R"MI_SAMPLE(' + text + ')MI_SAMPLE"\n'
    outputs = {TARGET: content}
    languages = []
    for language in ('English', 'Spanish', 'Portuguese'):
        ini = configparser.ConfigParser(interpolation=None)
        ini.optionxform = str
        ini.read(ROOT / ('lang/' + language + '.ini'), encoding='utf-8')
        languages.append(ini['MI_CATALOG'])
    strings = '// Generated by tools/mi/embed_catalog.py from lang/* [MI_CATALOG].\n'
    for key in languages[0]:
        values = [key] + [json.loads(language[key]) for language in languages]
        strings += '{ ' + ', '.join(json.dumps(value, ensure_ascii=False) for value in values) + ' },\n'
    outputs[ROOT / 'src/pc/mod_integrations/mi_catalog_strings.inc'] = strings
    for target, generated in outputs.items():
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != generated:
                raise SystemExit('Embedded MI data is stale; run python tools/mi/embed_catalog.py')
        else:
            target.write_text(generated, encoding='utf-8')


if __name__ == '__main__':
    main()
